import { chromium } from '@playwright/test';
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 640, height: 400 } });
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:12222/snowboard-sim');
const ready = (name) => p.waitForFunction((n) => document.querySelector('h1')?.textContent?.includes(n) && [...document.querySelectorAll('button')].some((x) => x.textContent.trim() === 'ride'), name, { timeout: 400000, polling: 1000 });
await ready('Appi');
console.log('default:', await p.evaluate(() => document.querySelector('h1').textContent));
await p.evaluate(() => { const s = document.querySelector('.panel select'); s.value = 'niseko-united'; s.dispatchEvent(new Event('change', { bubbles: true })); });
await ready('Niseko');
console.log('picked:', p.url(), await p.evaluate(() => [document.querySelector('h1').textContent, document.querySelector('.legend li:last-child').textContent.replace(/\s+/g, ' '), document.querySelectorAll('canvas.view').length, ...[...document.querySelectorAll('.panel select')].map((x) => x.value + ' / ' + x.options.length), 'cells ' + window.__snowboard.frame.width + 'x' + window.__snowboard.frame.height]));
console.log('errors:', errs);
await b.close();
